def get_food_warnings_for_drugs(drug_names: list[str]) -> dict:
    normalized = [name.lower().strip() for name in drug_names]
    
    results = {}
    all_foods_to_avoid = []
    seen_foods = set()
    
    for drug in normalized:
        if drug in FOOD_DRUG_WARNINGS:
            warnings = FOOD_DRUG_WARNINGS[drug]
            results[drug] = warnings
            for w in warnings:
                key = w["food"].lower()
                if key not in seen_foods:
                    seen_foods.add(key)
                    all_foods_to_avoid.append({
                        "food": w["food"],
                        "emoji": w["emoji"],
                        "affects_drugs": [drug],
                        "severity": w["severity"],
                        "advice": w["advice"],
                        "why": w["why"]
                    })
                else:
                    # Add this drug to existing entry
                    for item in all_foods_to_avoid:
                        if item["food"].lower() == key:
                            if drug not in item["affects_drugs"]:
                                item["affects_drugs"].append(drug)
                            # Escalate severity if higher
                            sev_order = {
                                "major": 3, 
                                "moderate": 2, 
                                "minor": 1
                            }
                            if (sev_order.get(w["severity"], 0) > sev_order.get(item["severity"], 0)):
                                item["severity"] = w["severity"]
                                
    # Sort by severity: major first
    sev_order = {"major": 3, "moderate": 2, "minor": 1}
    all_foods_to_avoid.sort(
        key=lambda x: sev_order.get(x["severity"], 0),
        reverse=True
    )
    
    return {
        "by_drug": results,
        "foods_to_avoid": all_foods_to_avoid,
        "total_warnings": len(all_foods_to_avoid),
        "has_major_warnings": any(f["severity"] == "major" for f in all_foods_to_avoid)
    }
